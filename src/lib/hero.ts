/**
 * Композиция героя.
 *
 * Всё, что здесь лежит, — это числа кадра, а не вкусовые отступы.
 * Композиция строится по золотому сечению: вертикаль на 61.8 % ширины,
 * горизонталь на 61.8 % высоты, ключевые элементы садятся на эти линии.
 * Симметрии нет ни по одной оси.
 *
 * В кадре героя лежит ОДНА фотография одним слоем. Ни холста воды, ни
 * второй копии снимка под маской переднего плана: обе уехали вместе с
 * приёмом и перекрытием. Всё, что осталось поверх снимка, — набор.
 */

/** Золотое сечение. Одно число на весь кадр. */
export const PHI = 0.618

/**
 * Вордмарк.
 *
 * Поле по бокам 3 % ширины — верхняя граница из задания (3–4 %).
 *
 * Кегль по-прежнему не задаётся, а ВЫВОДИТСЯ, но теперь из двух условий
 * сразу, и берётся меньшее:
 *
 *   - рост литеры ровно `WM_CAP` высоты экрана — это главное условие;
 *   - слово не шире, чем ширина кадра минус поля, — это ограничение.
 *
 * При 16:9 связывает первое: литера 22 % высоты даёт кегль 328 px и
 * слово шириной 1223 px из 1920, то есть до полей оно не дотягивает —
 * так и задумано, высота важнее. На узком экране (9:16) связывает
 * второе, и слово стоит во всю ширину, как стояло.
 */
export const WM_PAD = 0.03
/** Рост литеры в долях высоты экрана. */
export const WM_CAP = 0.22
/** Базовая линия слова — на горизонтали золотого сечения. */
export const WM_BASE = PHI

/**
 * На мобильном кадре базовая линия ниже — и это замер, а не вкус.
 *
 * Кадр 9:16 снят с той же точки, но вертикально: на 0.618 высоты у него
 * идёт не вода, а снежный гребень и паровой столб. Литеры «E» и «R»
 * ложатся на землю светлотой 0.427 и 0.431 и дают 2.20 и 2.18:1 — ниже
 * порога вдвое. Задание на такой случай говорит однозначно: двигать
 * элемент в тёмную зону, а не ставить подложку.
 */
export const WM_BASE_M = 0.78

/*
 * Отражения имени в воде здесь больше нет, и это не забывчивость.
 *
 * Без ряби искажать его нечем, и зеркальная копия остаётся зеркальной
 * копией: жёсткие геометрические литеры поверх настоящей ряби на
 * фотографии. На плотности, при которой оно вообще читается, оно
 * читается ошибкой набора, а не отражением.
 *
 * И вторая, решающая причина — геометрия. Имя уменьшилось до 22 %
 * высоты, базовая линия осталась на золотой горизонтали, а дальняя
 * кромка чаши на этом кадре идёт по диагонали: под левой третью слова
 * вода начинается только на 930-й строке при базовой линии на 667-й.
 * Отражаться там нечему — под литерами снег и каменный борт.
 */

/**
 * Кегль заголовка.
 *
 * Задание оставило кегль прежним, а вордмарк уменьшился, поэтому от
 * кегля имени заголовок больше не считается: он считается от ШИРИНЫ
 * кадра. Число выведено из прежней раскладки — там кегль имени был
 * `w * 0.94 / Σ` и заголовок вшестеро мельче, что при Σ = 3.721 даёт
 * ровно 4.21 % ширины. На 1920 это те же 80.8 px, что и было.
 */
export const TITLE_W = 0.0421

/**
 * На мобильной отношение другое, и это не поблажка, а арифметика: имя
 * во всю ширину узкого экрана даёт литеру ростом всего 8 % высоты, и
 * при делении на 5.5 заголовок ушёл бы под кегль подписей по кромкам.
 * Считается от кегля имени: на 9:16 он width-driven и не изменился.
 */
export const TITLE_RATIO_M = 1 / 3.2

/**
 * Воздух между базовой линией имени и первой строкой заголовка, в долях
 * кегля имени. Тридцать процентов, а не десять: под базовой линией
 * лежит отражение, и заголовок обязан начинаться там, где оно уже
 * растворилось, — иначе строка читается по призраку самой себя.
 */
export const TITLE_GAP = 0.3

/** Ширины литер TERMA в em. Дублируют метрики гарнитуры. */
export const WM_LETTERS = ['T', 'E', 'R', 'M', 'A'] as const
