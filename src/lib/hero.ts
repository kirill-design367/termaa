/**
 * Композиция героя.
 *
 * Всё, что здесь лежит, — это числа кадра, а не вкусовые отступы.
 * Композиция строится по золотому сечению: вертикаль на 61.8 % ширины,
 * горизонталь на 61.8 % высоты, ключевые элементы садятся на эти линии
 * и на их пересечение. Симметрии нет ни по одной оси.
 */

/** Золотое сечение. Одно число на весь кадр. */
export const PHI = 0.618

/**
 * Вордмарк.
 *
 * Поле по бокам 3 % ширины — верхняя граница из задания (3–4 %). Кегль
 * не задаётся, он ВЫВОДИТСЯ: слово во всю ширину при известной сумме
 * ширин литер даёт ровно один кегль. При 16:9 из этого выходит литера
 * ростом 32.5 % высоты экрана — требование «не меньше 30 %» выполняется
 * само, без подгонки.
 */
export const WM_PAD = 0.03
/** Базовая линия слова — на горизонтали золотого сечения. */
export const WM_BASE = PHI

/**
 * На мобильном кадре базовая линия ниже — и это замер, а не вкус.
 *
 * Кадр 9:16 снят с той же точки, но вертикально: на 0.618 высоты у него
 * идёт не вода, а снежный гребень и паровой столб. Литеры «E» и «R»
 * ложатся на землю светлотой 0.427 и 0.431 и дают 2.20 и 2.18:1 — ниже
 * порога вдвое. Задание на такой случай говорит однозначно: двигать
 * элемент в тёмную зону, а не ставить подложку. На 0.78 всё слово лежит
 * на глубокой воде, худшая литера держит около 5:1, и ниже слова
 * остаётся место под отражение.
 */
export const WM_BASE_M = 0.78

/**
 * Заголовок мельче имени в 6 раз — дальний край вилки 5–6 из задания.
 * Взят дальний, а не середина: заголовок стоит в небе, которое светлеет
 * вправо, и каждый лишний пиксель кегля уводит строку в светлое.
 * Считается от кегля имени, а не от вьюпорта: связь между двумя
 * размерами должна держаться на любом экране.
 */
export const TITLE_RATIO = 1 / 6

/**
 * На мобильной отношение другое, и это не поблажка, а арифметика: имя
 * во всю ширину узкого экрана даёт литеру ростом всего 8 % высоты, и
 * при делении на 5.5 заголовок ушёл бы под кегль подписей по кромкам.
 * Контраст масштабов там держится за счёт самой пропорции экрана.
 */
export const TITLE_RATIO_M = 1 / 3.2

/** Минимальный воздух между заголовком и именем, в пикселях. */
export const TITLE_GAP_MIN = 18

/**
 * Сколько воздуха между низом заголовка и верхом литер вордмарка.
 * В долях кегля вордмарка — иначе на широком экране зазор уплывёт.
 */
export const TITLE_GAP = 0.09

/**
 * Что стоит ближе вордмарка и обязано его перекрывать.
 *
 * Слово стоит в чаше бассейна. Плита крыши и чёрные стойки остекления
 * ближе к камере, значит они режут литеры — это и есть глубина, а не
 * надпись поверх картинки. Полигоны сняты по сетке с самого кадра и
 * испечены в маску `fg-desktop`; здесь только адрес.
 *
 * Пересечение по кадру считается так: наклонная кромка крыши опускается
 * ниже верха литер на участке u 0.52…0.63, то есть срезает верхний
 * правый угол «Р» и верхний левый угол «М». Стойки на u 0.766, 0.790 и
 * 0.940 проходят вертикальными полосами сквозь «М» и «А».
 */
export const FG_MASK = '/img/fg-desktop.webp'

/** Ширины литер TERMA в em. Дублируют метрики гарнитуры. */
export const WM_LETTERS = ['T', 'E', 'R', 'M', 'A'] as const
