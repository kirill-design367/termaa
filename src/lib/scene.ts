/**
 * Прогресс сцены героя, 0..1.
 *
 * Один мастер-таймлайн пишет сюда значение, а всё, что от него зависит —
 * объёмный пар, испечённый поток, фон полотна — читает. Прямых связей
 * между компонентами нет, поэтому любой из них можно выключить,
 * не ломая остальные.
 */
let hero = 0

export const setHeroProgress = (v: number) => {
  hero = v
}

export const heroProgress = () => hero
